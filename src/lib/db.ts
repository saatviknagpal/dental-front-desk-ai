// Postgres storage.
//  - DATABASE_URL set  → node-postgres pool (Supabase in prod/demo).
//  - DATABASE_URL unset → PGlite (Postgres compiled to WASM, in-process) for tests
//    and zero-setup local dev. Same SQL dialect in both.
//
// Timestamps for scheduling are stored as practice-local wall-clock TEXT
// "YYYY-MM-DD HH:MM" (sorts correctly; no timezone conversion surprises).

import { PGlite } from "@electric-sql/pglite";
import pg from "pg";

const SCHEMA = `
CREATE TABLE IF NOT EXISTS providers (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  title TEXT NOT NULL,
  services TEXT NOT NULL                       -- comma-separated appointment types
);

CREATE TABLE IF NOT EXISTS patients (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name TEXT NOT NULL,
  last_name TEXT NOT NULL,
  dob TEXT NOT NULL,                           -- YYYY-MM-DD
  phone TEXT NOT NULL,                         -- 10 digits
  insurance_name TEXT,                         -- NULL = self-pay
  household_id INTEGER,                        -- family members share a household
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_patients_dob ON patients (dob);

CREATE TABLE IF NOT EXISTS appointments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id INTEGER NOT NULL REFERENCES patients(id),
  provider_id INTEGER NOT NULL REFERENCES providers(id),
  type TEXT NOT NULL,                          -- cleaning | checkup | emergency
  start_ts TEXT NOT NULL,
  end_ts TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'booked',       -- booked | cancelled
  notes TEXT,
  emergency_summary TEXT,
  cancel_reason TEXT,
  session_id TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_appts_patient ON appointments (patient_id, status);
CREATE INDEX IF NOT EXISTS idx_appts_start ON appointments (start_ts);

CREATE TABLE IF NOT EXISTS slots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_id INTEGER NOT NULL REFERENCES providers(id),
  start_ts TEXT NOT NULL,                      -- 30-minute slot start
  status TEXT NOT NULL DEFAULT 'open',         -- open | booked | blocked
  appointment_id INTEGER REFERENCES appointments(id),
  UNIQUE (provider_id, start_ts)
);
CREATE INDEX IF NOT EXISTS idx_slots_open ON slots (start_ts) WHERE status = 'open';
CREATE INDEX IF NOT EXISTS idx_slots_appt ON slots (appointment_id);

CREATE TABLE IF NOT EXISTS notifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL,                          -- emergency | human_handoff | callback
  urgency TEXT NOT NULL,                       -- high | normal
  patient_id INTEGER REFERENCES patients(id),
  summary TEXT NOT NULL,
  session_id TEXT,
  acknowledged BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TEXT NOT NULL
);

-- Conversation state lives in the DB (not server memory) so the web tier is
-- stateless and can scale horizontally.
CREATE TABLE IF NOT EXISTS sessions (
  id TEXT PRIMARY KEY,
  started_at TEXT NOT NULL,
  last_active_at TEXT NOT NULL,
  model TEXT,
  llm_messages JSONB NOT NULL DEFAULT '[]',    -- provider-neutral chat history
  access JSONB NOT NULL DEFAULT '{"verified":[],"household":[]}',
  failed_verifications INTEGER NOT NULL DEFAULT 0,
  rating INTEGER,                              -- 1 thumbs up, -1 thumbs down
  feedback_comment TEXT,
  judge JSONB                                  -- LLM-judge verdict (npm run evals:prod)
);
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS judge JSONB;
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS usage JSONB;               -- cumulative tokens + cost

-- Eval history (written by npm run evals). One run = one model x all scenarios x k.
CREATE TABLE IF NOT EXISTS eval_runs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started_at TEXT NOT NULL,
  model TEXT NOT NULL,
  judge_model TEXT,
  k INTEGER NOT NULL,
  scenarios INTEGER NOT NULL,
  pass_k INTEGER NOT NULL,                     -- scenarios that passed all k runs
  runs_passed INTEGER NOT NULL,
  runs_total INTEGER NOT NULL,
  metrics JSONB NOT NULL                       -- tool accuracy, hallucination, redundancy, tone, latency, tokens, cost
);
-- One row per scenario run: outcome checks (with the DB records they saw), judge verdict, usage.
CREATE TABLE IF NOT EXISTS eval_results (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id INTEGER NOT NULL REFERENCES eval_runs(id) ON DELETE CASCADE,
  scenario_id TEXT NOT NULL,
  title TEXT NOT NULL,
  rep INTEGER NOT NULL,
  passed BOOLEAN NOT NULL,
  checks JSONB NOT NULL,
  judge JSONB,
  usage JSONB,
  turns INTEGER NOT NULL,
  seconds INTEGER NOT NULL,
  latencies_ms JSONB NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_eval_results_run ON eval_results (run_id);
-- Full trajectory: patient message, each LLM decision (tokens, cost, latency), each tool call (args + result), reply.
CREATE TABLE IF NOT EXISTS eval_steps (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  result_id INTEGER NOT NULL REFERENCES eval_results(id) ON DELETE CASCADE,
  seq INTEGER NOT NULL,
  role TEXT NOT NULL,                          -- user | llm | tool | assistant
  content JSONB NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_eval_steps_result ON eval_steps (result_id, seq);

-- Human-readable transcript (user/assistant text + tool events) for the staff view.
CREATE TABLE IF NOT EXISTS messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id TEXT NOT NULL,
  role TEXT NOT NULL,                          -- user | assistant | tool
  content TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_messages_session ON messages (session_id, id);

-- Multi-tenant: rows belong to a practice (see src/lib/practice.ts). Slots and
-- appointments inherit their practice through provider_id / patient_id.
ALTER TABLE providers ADD COLUMN IF NOT EXISTS practice_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE patients ADD COLUMN IF NOT EXISTS practice_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE notifications ADD COLUMN IF NOT EXISTS practice_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS practice_id INTEGER NOT NULL DEFAULT 1;
ALTER TABLE patients ADD COLUMN IF NOT EXISTS email TEXT;                -- optional, for confirmations
CREATE INDEX IF NOT EXISTS idx_patients_practice_dob ON patients (practice_id, dob);
CREATE UNIQUE INDEX IF NOT EXISTS uq_patients_identity ON patients (practice_id, lower(first_name), lower(last_name), dob);
CREATE INDEX IF NOT EXISTS idx_sessions_practice ON sessions (practice_id, last_active_at);
CREATE INDEX IF NOT EXISTS idx_notifications_practice ON notifications (practice_id, id);

-- Background jobs (transactional outbox). See src/lib/queue.ts.
CREATE TABLE IF NOT EXISTS jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL,
  payload JSONB NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',      -- pending | running | done | failed
  attempts INTEGER NOT NULL DEFAULT 0,
  max_attempts INTEGER NOT NULL DEFAULT 5,
  run_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  locked_at TIMESTAMPTZ,
  finished_at TIMESTAMPTZ,
  last_error TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_jobs_due ON jobs (run_at) WHERE status = 'pending';
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS practice_id INTEGER;
CREATE INDEX IF NOT EXISTS idx_jobs_failed ON jobs (practice_id, id) WHERE status = 'failed';
CREATE INDEX IF NOT EXISTS idx_jobs_running ON jobs (locked_at) WHERE status = 'running';
CREATE INDEX IF NOT EXISTS idx_jobs_done ON jobs (finished_at) WHERE status = 'done';

-- Failed identity checks, so the lockout holds across chats (not just within one).
CREATE TABLE IF NOT EXISTS verification_failures (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name_key TEXT NOT NULL,                      -- normalized full name that was tried
  session_id TEXT,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_verification_failures ON verification_failures (name_key, created_at);
ALTER TABLE verification_failures ADD COLUMN IF NOT EXISTS caller TEXT;
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS busy_until TIMESTAMPTZ;      -- a turn is in progress
`;

export type Row = Record<string, unknown>;

/** Minimal query interface shared by the pool, PGlite, and transactions. */
export interface Q {
  all<T = Row>(sql: string, params?: unknown[]): Promise<T[]>;
  get<T = Row>(sql: string, params?: unknown[]): Promise<T | undefined>;
  run(sql: string, params?: unknown[]): Promise<{ rowCount: number; rows: Row[] }>;
}

interface Backend {
  q: Q;
  transaction<T>(fn: (tx: Q) => Promise<T>): Promise<T>;
  exec(sql: string): Promise<void>;
  close(): Promise<void>;
}

type Raw = (sql: string, params?: unknown[]) => Promise<{ rows: Row[]; rowCount: number }>;

function makeQ(raw: Raw): Q {
  return {
    all: async <T>(sql: string, params: unknown[] = []) => (await raw(sql, params)).rows as T[],
    get: async <T>(sql: string, params: unknown[] = []) => (await raw(sql, params)).rows[0] as T | undefined,
    run: (sql: string, params: unknown[] = []) => raw(sql, params),
  };
}

function pgBackend(url: string): Backend {
  const needsSsl = /supabase|sslmode=require/.test(url) || process.env.DATABASE_SSL === "true";
  const pool = new pg.Pool({
    connectionString: url,
    ssl: needsSsl ? { rejectUnauthorized: false } : undefined,
    max: Number(process.env.DATABASE_POOL_MAX || 5),
  });
  const rawFor =
    (c: pg.Pool | pg.PoolClient): Raw =>
    async (sql, params) => {
      const r = await c.query(sql, params as unknown[]);
      return { rows: r.rows, rowCount: r.rowCount ?? 0 };
    };
  return {
    q: makeQ(rawFor(pool)),
    async transaction(fn) {
      const client = await pool.connect();
      try {
        await client.query("BEGIN");
        const result = await fn(makeQ(rawFor(client)));
        await client.query("COMMIT");
        return result;
      } catch (err) {
        await client.query("ROLLBACK").catch(() => undefined);
        throw err;
      } finally {
        client.release();
      }
    },
    exec: async (sql) => void (await pool.query(sql)),
    close: () => pool.end(),
  };
}

function pgliteBackend(dataDir?: string): Backend {
  const db = new PGlite(dataDir);
  const rawFor =
    (c: { query: PGlite["query"] }): Raw =>
    async (sql, params) => {
      const r = await c.query<Row>(sql, params as unknown[]);
      return { rows: r.rows, rowCount: r.affectedRows ?? r.rows.length };
    };
  // PGlite is single-connection: serialize transactions so they never interleave.
  let chain: Promise<unknown> = Promise.resolve();
  return {
    q: makeQ(rawFor(db)),
    transaction<T>(fn: (tx: Q) => Promise<T>) {
      const next = chain.then(() => db.transaction((tx) => fn(makeQ(rawFor(tx as unknown as { query: PGlite["query"] })))));
      chain = next.catch(() => undefined);
      return next as Promise<T>;
    },
    exec: async (sql) => void (await db.exec(sql)),
    close: () => db.close(),
  };
}

const g = globalThis as unknown as { __dentalDb?: { key: string; backend: Backend; ready: Promise<void> } };

// Includes the schema size so a hot-reloaded schema change re-runs the (idempotent) DDL.
function backendKey() {
  return `${process.env.DATABASE_URL || `pglite:${process.env.PGLITE_DIR || "memory"}`}#${SCHEMA.length}`;
}

/** Get the shared backend (one pool per process), creating the schema on first use. */
async function backend(): Promise<Backend> {
  const key = backendKey();
  if (!g.__dentalDb || g.__dentalDb.key !== key) {
    g.__dentalDb?.backend.close().catch(() => undefined); // don't leak the old pool's connections
    const b = process.env.DATABASE_URL ? pgBackend(process.env.DATABASE_URL) : pgliteBackend(process.env.PGLITE_DIR || undefined);
    g.__dentalDb = { key, backend: b, ready: b.exec(SCHEMA) };
  }
  await g.__dentalDb.ready;
  return g.__dentalDb.backend;
}

export const db: Q = {
  all: async (sql, params) => (await backend()).q.all(sql, params),
  get: async (sql, params) => (await backend()).q.get(sql, params),
  run: async (sql, params) => (await backend()).q.run(sql, params),
};

/** Run fn in a transaction; rolls back if it throws. */
export async function transaction<T>(fn: (tx: Q) => Promise<T>): Promise<T> {
  return (await backend()).transaction(fn);
}

/** Wipe all data (demo reset / tests). Keeps the schema. */
export async function truncateAll(): Promise<void> {
  // Eval history tables are intentionally kept across demo resets.
  await (await backend()).exec("TRUNCATE jobs, verification_failures, messages, sessions, notifications, slots, appointments, patients, providers RESTART IDENTITY CASCADE");
}

export async function closeDb(): Promise<void> {
  if (g.__dentalDb) {
    await g.__dentalDb.backend.close();
    g.__dentalDb = undefined;
  }
}
